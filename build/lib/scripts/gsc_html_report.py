#!/usr/bin/env python3
"""gsc_html_report.py — Generate CISO-ready HTML report from GSC findings.

Usage: python3 gsc.py scan ./repo --ci --json | python3 scripts/gsc_html_report.py > report.html
   or: python3 scripts/gsc_html_report.py findings.json > report.html
"""
import json, sys, hashlib
from datetime import datetime, timezone
from pathlib import Path

SEVERITY_COLORS = {"CRITICAL": "#dc3545", "HIGH": "#fd7e14", "MEDIUM": "#ffc107", "LOW": "#28a745"}
CWE_MAP = {"GS005": "CWE-89", "GS020": "CWE-79", "GS029": "CWE-798", "GS008": "CWE-95",
           "GS007": "CWE-502", "GS010": "CWE-703", "GS018": "CWE-754", "GS031": "CWE-250"}

def render(findings: list, title: str = "GSC Security Report") -> str:
    total = len(findings)
    by_sev = {}
    for f in findings:
        s = f.get("category", "MEDIUM")
        by_sev[s] = by_sev.get(s, 0) + 1
    by_rule = {}
    for f in findings:
        r = f.get("rule_id", "?")
        by_rule[r] = by_rule.get(r, 0) + 1

    rows = ""
    for i, f in enumerate(findings):
        sev = f.get("category", "MEDIUM")
        rid = f.get("rule_id", "?")
        title = f.get("title", f.get("pattern_title", ""))[:80]
        file = f.get("file_path", f.get("file", "?"))
        line = f.get("line", f.get("line_number", "?"))
        cwe = CWE_MAP.get(rid, "—")
        color = SEVERITY_COLORS.get(sev, "#6c757d")
        rows += f"""<tr style="border-left:4px solid {color}">
            <td style="color:{color};font-weight:bold">{sev}</td>
            <td><code>{rid}</code></td>
            <td>{title}</td>
            <td><code>{file}</code></td>
            <td>{line}</td>
            <td>{cwe}</td></tr>"""

    rule_rows = ""
    for r, c in sorted(by_rule.items(), key=lambda x: -x[1]):
        rule_rows += f"<tr><td><code>{r}</code></td><td>{c}</td></tr>"

    return f"""<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">
<title>{title}</title><style>
*{{margin:0;padding:0;box-sizing:border-box}}
body{{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif;background:#0d1117;color:#c9d1d9;padding:2rem}}
h1{{color:#58a6ff;font-size:1.8rem;margin-bottom:.25rem}}
.subtitle{{color:#8b949e;margin-bottom:2rem}}
.cards{{display:grid;grid-template-columns:repeat(auto-fit,minmax(140px,1fr));gap:1rem;margin-bottom:2rem}}
.card{{background:#161b22;border:1px solid #30363d;border-radius:8px;padding:1.2rem;text-align:center}}
.card .num{{font-size:2rem;font-weight:bold}}
.card .label{{color:#8b949e;font-size:.85rem;margin-top:.3rem}}
table{{width:100%;border-collapse:collapse;margin-bottom:2rem;background:#161b22;border-radius:8px;overflow:hidden}}
th,td{{padding:.6rem .8rem;text-align:left;border-bottom:1px solid #30363d}}
th{{background:#21262d;font-weight:600;font-size:.85rem;color:#8b949e}}
code{{background:#21262d;padding:.1rem .3rem;border-radius:3px;font-size:.85rem}}
.section{{margin-top:2rem}}
.section h2{{color:#58a6ff;margin-bottom:1rem;font-size:1.2rem}}
.footer{{color:#8b949e;font-size:.8rem;margin-top:3rem;text-align:center}}
</style></head><body>
<h1>🛡️ {title}</h1>
<p class="subtitle">Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} • {total} findings</p>

<div class="cards">
<div class="card"><div class="num" style="color:#dc3545">{by_sev.get('CRITICAL',0)}</div><div class="label">CRITICAL</div></div>
<div class="card"><div class="num" style="color:#fd7e14">{by_sev.get('HIGH',0)}</div><div class="label">HIGH</div></div>
<div class="card"><div class="num" style="color:#ffc107">{by_sev.get('MEDIUM',0)}</div><div class="label">MEDIUM</div></div>
<div class="card"><div class="num" style="color:#28a745">{by_sev.get('LOW',0)}</div><div class="label">LOW</div></div>
<div class="card"><div class="num">{total}</div><div class="label">TOTAL</div></div>
</div>

<div class="section"><h2>📋 Findings</h2>
<table><thead><tr><th>Severity</th><th>Rule</th><th>Title</th><th>File</th><th>Line</th><th>CWE</th></tr></thead>
<tbody>{rows}</tbody></table></div>

<div class="section"><h2>📊 By Rule</h2>
<table style="max-width:400px"><thead><tr><th>Rule</th><th>Count</th></tr></thead>
<tbody>{rule_rows}</tbody></table></div>

<div class="section"><h2>🔗 What's Next</h2>
<p style="color:#8b949e">
✅ Run <code>gsc pof generate &lt;finding_key&gt;</code> to get auto-fix<br>
✅ Deploy Self-Healing CI for automatic PRs<br>
✅ Enable Federated Learning to improve over time</p></div>

<div class="footer">Generated by GSC — Git Security Checker • github.com/poliakarmai/gsc</div>
</body></html>"""

if __name__ == "__main__":
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text())
    else:
        data = json.load(sys.stdin)
    # Handle both flat array and {vulnerabilities: [...]} wrapper
    findings = data if isinstance(data, list) else data.get("vulnerabilities", data.get("findings", []))
    print(render(findings))
